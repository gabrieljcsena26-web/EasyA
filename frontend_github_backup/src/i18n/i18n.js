export function getStoredLang(opts = {}) {
  const storageKey = (opts && opts.storageKey) ? String(opts.storageKey) : 'ea_lang'
  try {
    let v = localStorage.getItem(storageKey)
    // migration: older builds used ea_lang
    if (!v && storageKey !== 'ea_lang') v = localStorage.getItem('ea_lang')
    const norm = normalizeLangCode(v)
    if (norm && MESSAGES[norm]) return norm
  } catch (_) {}

  // If admin config is cached, default to the establishment language.
  try {
    const raw = localStorage.getItem('ea_admin_config')
    if (raw) {
      const cfg = JSON.parse(raw)
      const bizLangRaw = cfg?.business?.idioma_padrao || cfg?.business?.lang || cfg?.business?.language
      const normBiz = normalizeLangCode(bizLangRaw)
      if (normBiz && MESSAGES[normBiz]) return normBiz
    }
  } catch (_) {}

  const nav = (typeof navigator !== 'undefined' && navigator.language) ? navigator.language : ''
  const normNav = normalizeLangCode(nav)
  if (normNav && MESSAGES[normNav]) return normNav
  return DEFAULT_LANG
}

export function t(lang, key) {
  const norm = normalizeLangCode(lang)
  const dict = MESSAGES[norm] || MESSAGES[DEFAULT_LANG]
  return dict[key] || (MESSAGES[DEFAULT_LANG] && MESSAGES[DEFAULT_LANG][key]) || key
}
